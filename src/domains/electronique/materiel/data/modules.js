/** Adresse I2C au format 0x3C. */
export const hex = (a) => `0x${a.toString(16).toUpperCase().padStart(2, '0')}`

/** Table « adresse → modules » de toutes les adresses connues. */
export function addressTable() {
  const map = new Map()
  for (const m of MODULES) {
    for (const a of [...(m.i2c ?? []), ...(m.i2cExtra ?? [])]) {
      if (!map.has(a)) map.set(a, [])
      map.get(a).push(m)
    }
  }
  return [...map.entries()].sort((a, b) => a[0] - b[0])
}
