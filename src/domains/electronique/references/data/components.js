// ── Transistors ──────────────────────────────────────────────────────────────────
const bjt = (order) =>
  order.map((t, i) => {
    const role = { C: 'Collecteur', B: 'Base', E: 'Émetteur' }[t]
    return pin(i + 1, t, role, t === 'B' ? 'ctl' : 'term')
  })
const fet = (order) =>
  order.map((t, i) => {
    const role = { G: 'Grille', D: 'Drain', S: 'Source' }[t]
    return pin(i + 1, t, role, t === 'G' ? 'ctl' : 'term')
  })

