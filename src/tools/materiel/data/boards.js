/** Étiquettes radio d'une carte (pour les filtres). */
export function wirelessTags(board) {
  if (board.wirelessTags) return board.wirelessTags
  const text = board.wireless.join(' ')
  const tags = []
  if (/Wi-Fi/.test(text)) tags.push('wifi')
  if (/Bluetooth/.test(text)) tags.push('bt')
  if (/802\.15\.4/.test(text)) tags.push('802154')
  return tags
}
