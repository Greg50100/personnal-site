/** Analyse « NOM | étiquettes » en { name, tags, valeurs }. */
export function parsePin(spec) {
  if (spec === 'gap') return { gap: true, name: '', tags: new Set(), values: {} }
  const [name, rest = ''] = spec.split(' | ')
  const pin = { name, tags: new Set(), values: {} }
  for (const token of rest.split(' ').filter(Boolean)) {
    const [key, value] = token.split('=')
    pin.tags.add(key)
    if (value) pin.values[key] = value
  }
  return pin
}
