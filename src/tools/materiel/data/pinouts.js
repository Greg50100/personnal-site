/**
 * BROCHAGES DES CARTES
 * --------------------
 * Ordre physique des broches, d'après les documents des fabricants (`source`). Chaque broche est décrite par
 * « NOM | étiquettes » :
 *   pwr, gnd, nc, ctl (commande : EN, RST, AREF…), gpio=N (numéro réel), in (entrée seulement),
 *   adc=…, adc2 (ADC2 des ESP, inutilisable avec le Wi-Fi), dac=…, i2c=SDA|SCL, spi=MOSI|MISO|SCK|CS,
 *   uart=TX|RX, pwm, i2s=…, onewire, usb=D+|D−, usbser (liaison USB-série), boot (broche de démarrage),
 *   flash (mémoire flash), psram, led, wake (réveil), int (interruption), id (EEPROM des HAT).
 * 'gap' laisse un espace entre deux connecteurs.
 *
 * Disposition 'columns' : left / right de haut en bas (top et bottom nomment ce qui est en haut et en bas de la carte).
 * Disposition 'rows' : top / bottom de gauche à droite, USB à gauche ; extra : connecteur double supplémentaire.
 * numbers : numérotation des broches { left: [début, pas], right: [début, pas] }.
 */

